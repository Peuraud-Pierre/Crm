"""Émet le SQL créant ce que décrit types.ts mais qui manque à la base locale.

usage: fill_missing.py schema.json DB_URL phase
  phase=tables : enums, tables, columns, primary keys, FKs
  phase=views  : missing views created as tables
  phase=funcs  : missing RPC functions created as harmless stubs
"""
import json, re, subprocess, sys

schema = json.load(open(sys.argv[1]))
DB, phase = sys.argv[2], sys.argv[3]
# Tables créées par une migration : on laisse la migration les créer (avec RLS, index, triggers).
EXCLUDE = set(open(sys.argv[4]).read().split()) if len(sys.argv) > 4 else set()


def q(sql):
    out = subprocess.run(["psql", DB, "-At", "-F", "\t", "-c", sql], capture_output=True, text=True, check=True).stdout
    return [line.split("\t") for line in out.splitlines() if line]


def ident(n):
    return '"' + n.replace('"', '""') + '"'


rels_existing = {r[0]: r[1] for r in q("select c.relname, c.relkind from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public'")}
cols_existing = {}
for t, c, typ in q("select table_name, column_name, udt_name from information_schema.columns where table_schema='public'"):
    cols_existing.setdefault(t, {})[c] = typ
enums_existing = {r[0] for r in q("select t.typname from pg_type t join pg_namespace n on n.oid=t.typnamespace where n.nspname='public' and t.typtype='e'")}
funcs_existing = {r[0] for r in q("select p.proname from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'")}

# Types que l'heuristique devine mal (constatés sur les migrations).
OVERRIDES = {
    ("cryptedmessage", "chat_id"): "text",
    ("plan_layout_handpick", "id"): "text",
    ("newsletter_api_logs", "req_id"): "text",
    ("newsletter_api_logs", "ts"): "timestamptz",
    ("newsletter_send_runs", "triggered_by"): "uuid",
    # pgp_sym_encrypt/decrypt (apple-liaison, cypher migrations/001) : bytea.
    ("apple_calendar_connections", "icloud_app_password_encrypted"): "bytea",
}
OVERRIDES_ANY = {"entity_id": "text", "session_id": "text", "debut": "timestamptz", "fin": "timestamptz", "snapshot_month": "date"}
UUID_NAMES = {"owner", "by", "created_by", "updated_by", "assigned_to", "author", "sender", "user", "uploaded_by", "reviewed_by"}


def fk_targets(table):
    return {c: (r["ref"], r["refcols"][i]) for r in table["rels"] for i, c in enumerate(r["columns"]) if i < len(r["refcols"])}


def sql_type(table_name, col, ts, fks, seen=()):
    base = ts.replace("| null", "").strip()
    m = re.match(r'Database\["public"\]\["Enums"\]\["(\w+)"\](\[\])?', base)
    if m:
        return ident(m.group(1)) + ("[]" if m.group(2) else "")
    if base == "Json":
        return "jsonb"
    if base == "boolean":
        return "boolean"
    if base == "number":
        return "bigint" if col == "id" or col.endswith("_id") else "numeric"
    if base == "number[]":
        return "numeric[]"
    if (table_name, col) in OVERRIDES:
        return OVERRIDES[(table_name, col)]
    if col in OVERRIDES_ANY:
        return OVERRIDES_ANY[col]
    if base == "string[]":
        return "uuid[]" if col.endswith("_ids") else "text[]"
    if base == "string":
        if col in fks:
            ref, refcol = fks[col]
            # Type of the referenced column, from the live DB first, then types.ts.
            live = cols_existing.get(ref, {}).get(refcol)
            if live:
                return {"int8": "bigint", "int4": "integer", "varchar": "text", "timestamptz": "timestamptz"}.get(live, live)
            t = schema["tables"].get(ref)
            if t and refcol in t["row"] and (ref, refcol) not in seen:
                return sql_type(ref, refcol, t["row"][refcol], fk_targets(t), seen + ((ref, refcol),))
            return "uuid"
        if col == "id" or col.endswith("_id") or col in UUID_NAMES:
            return "uuid"
        if col.endswith("_at") or col in ("timestamp", "last_seen", "last_login"):
            return "timestamptz"
        if col == "date" or col.endswith("_date") or col.startswith("date_"):
            return "date"
        return "text"
    return "text"


def default_for(col, typ, ts_row, ts_insert):
    optional = ts_insert is not None and True  # all inserts in this types.ts are optional
    if col == "id" and typ == "uuid":
        return " default gen_random_uuid()"
    if col == "id" and typ == "bigint":
        return " generated by default as identity"
    if col in ("created_at", "updated_at") and typ == "timestamptz":
        return " default now()"
    if typ == "boolean" and "null" not in ts_row:
        return " default false"
    if typ == "jsonb" and "null" not in ts_row:
        return " default '{}'::jsonb"
    return ""


out = []
if phase == "tables":
    for name, vals in schema["enums"].items():
        if name not in enums_existing:
            labels = ", ".join("'" + v.replace("'", "''") + "'" for v in vals)
            out.append(f"create type public.{ident(name)} as enum ({labels});")
    for tname, t in schema["tables"].items():
        fks = fk_targets(t)
        if tname not in rels_existing and tname in EXCLUDE:
            continue
        if tname in rels_existing and rels_existing[tname] not in ("r", "p"):
            continue  # exists as a view: leave it
        defs = []
        for col, ts in t["row"].items():
            typ = sql_type(tname, col, ts, fks)
            if tname in cols_existing and col in cols_existing[tname]:
                continue
            d = default_for(col, typ, ts, t["insert"].get(col))
            notnull = " not null" if (col == "id") else ""
            defs.append((col, f"{ident(col)} {typ}{d}{notnull}"))
        if tname not in rels_existing:
            pk = ", primary key (id)" if "id" in t["row"] else ""
            out.append(f"create table public.{ident(tname)} ({', '.join(d for _, d in defs)}{pk});")
            out.append(f"grant all on public.{ident(tname)} to anon, authenticated, service_role;")
        else:
            for _, d in defs:
                out.append(f"alter table public.{ident(tname)} add column if not exists {d};")
    out.append("-- FK")
    for tname, t in schema["tables"].items():
        for r in t["rels"]:
            if r["ref"] not in schema["tables"]:
                continue
            cols = ", ".join(ident(c) for c in r["columns"])
            rcols = ", ".join(ident(c) for c in r["refcols"])
            uq = f"{r['ref']}_{'_'.join(r['refcols'])}_uq"[:60]
            out.append(
                "do $$ begin "
                f"begin alter table public.{ident(r['ref'])} add constraint {ident(uq)} unique ({rcols}); exception when others then null; end; "
                f"begin alter table public.{ident(tname)} add constraint {ident(r['name'][:63])} foreign key ({cols}) references public.{ident(r['ref'])} ({rcols}) on delete cascade; exception when others then null; end; "
                "end $$;"
            )
elif phase == "views":
    for vname, v in schema["views"].items():
        if vname in rels_existing:
            continue
        defs = [f"{ident(c)} {sql_type(vname, c, ts, fk_targets(v))}" for c, ts in v["row"].items()]
        out.append(f"create table public.{ident(vname)} ({', '.join(defs)});")
        out.append(f"grant all on public.{ident(vname)} to anon, authenticated, service_role;")
elif phase == "funcs":
    for fname, body in schema["functions"].items():
        if fname in funcs_existing:
            continue
        out.append(f"-- missing function: {fname}")
print("\n".join(out))
