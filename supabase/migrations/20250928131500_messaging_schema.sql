-- Messaging schema alignment

-- Ensure required tables exist ------------------------------------------------

create table if not exists public.groups (
    id uuid not null default gen_random_uuid(),
    name text not null,
    description text null,
    created_by uuid not null,
    created_at timestamp with time zone not null default now(),
    constraint groups_pkey primary key (id)
);

create table if not exists public.groupe_participant (
    id bigint generated by default as identity not null,
    group_id uuid not null default gen_random_uuid(),
    participant uuid null default gen_random_uuid(),
    constraint groupe_participant_pkey primary key (id)
);

create table if not exists public.created_chat (
    id_chat uuid not null default gen_random_uuid(),
    created_by uuid not null,
    with_id uuid not null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint created_chat_pkey primary key (id_chat)
);

create table if not exists public.messages (
    id bigserial not null,
    sender_id uuid not null,
    recipient_id uuid null,
    group_id uuid null,
    ciphertext_b64 text null,
    encrypted_key_b64 text null,
    iv_b64 text null,
    meta jsonb null default '{}'::jsonb,
    created_at timestamp with time zone not null default now(),
    files text null,
    read boolean null,
    chat_id uuid null,
    content text null,
    groupe_id uuid null,
    constraint messages_pkey primary key (id)
);

-- Synchronise columns ---------------------------------------------------------

alter table public.groups
    add column if not exists description text null,
    add column if not exists created_at timestamp with time zone default now();

alter table public.groupe_participant
    add column if not exists group_id uuid not null default gen_random_uuid(),
    add column if not exists participant uuid null default gen_random_uuid();

alter table public.created_chat
    add column if not exists created_at timestamp with time zone not null default now(),
    add column if not exists updated_at timestamp with time zone not null default now(),
    add column if not exists created_by uuid not null,
    add column if not exists with_id uuid not null;

alter table public.messages
    add column if not exists recipient_id uuid,
    add column if not exists group_id uuid,
    add column if not exists ciphertext_b64 text,
    add column if not exists encrypted_key_b64 text,
    add column if not exists iv_b64 text,
    add column if not exists meta jsonb default '{}'::jsonb,
    add column if not exists files text,
    add column if not exists read boolean,
    add column if not exists chat_id uuid,
    add column if not exists content text,
    add column if not exists groupe_id uuid;

