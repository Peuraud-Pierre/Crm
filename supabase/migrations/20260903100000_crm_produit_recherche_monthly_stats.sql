-- ============================================================
-- Classement mensuel des produits recherchés (CRM Analytics)
-- Date: 2026-09-03
--
-- Remplace crm_produit_recherche_stats (un total global par mois, sans
-- détail produit — migration 20260903090000) par un stockage par produit :
-- le widget "Produits les plus recherchés" doit pouvoir classer par nom de
-- produit sur une période passée, ce qu'un total seul ne permet pas. Voir
-- docs/superpowers/specs/2026-09-03-crm-produit-recherche-trend-design.md
--
-- Idempotent (guards IF EXISTS / DROP POLICY IF EXISTS / cron.unschedule).
-- ============================================================

BEGIN;

-- ── 1. Démantèlement de l'ancien stockage (total seul, superseded) ──────

DROP FUNCTION IF EXISTS public.snapshot_produit_recherche_stats();
DROP TABLE IF EXISTS public.crm_produit_recherche_stats;

-- ── 2. Nouvelle table : une ligne par (mois, produit) ────────────────────

CREATE TABLE IF NOT EXISTS public.crm_produit_recherche_monthly_stats (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_month date NOT NULL,
    product_name   text NOT NULL,
    total_entries  integer NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT crm_produit_recherche_monthly_stats_month_product_key
        UNIQUE (snapshot_month, product_name)
);

-- ── 3. RLS : lecture gatée sur crm.view, pas d'écriture applicative ──────

ALTER TABLE public.crm_produit_recherche_monthly_stats ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "crm.view can read produit recherche monthly stats" ON public.crm_produit_recherche_monthly_stats;
CREATE POLICY "crm.view can read produit recherche monthly stats"
    ON public.crm_produit_recherche_monthly_stats FOR SELECT
    TO authenticated
    USING (public.user_has_permission(auth.uid(), 'crm.view'));

-- ── 4. Fonction de snapshot ────────────────────────────────────────────
-- brief peut être un jsonb natif OU une chaîne JSON encodée (cas connu côté
-- front : Client.brief?: FicheAppro | string | null). La normalisation du
-- nom (1ère lettre majuscule, reste minuscule, trim) reproduit exactement
-- celle du front (AnalyticsContext.tsx) pour que les libellés correspondent.

CREATE OR REPLACE FUNCTION public.snapshot_produit_recherche_monthly_stats()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
    v_month date := date_trunc('month', now())::date;
BEGIN
    -- Reset du mois courant avant réinsertion : un produit qui n'a plus
    -- aucune recherche active ne doit pas garder un total périmé.
    DELETE FROM public.crm_produit_recherche_monthly_stats WHERE snapshot_month = v_month;

    INSERT INTO public.crm_produit_recherche_monthly_stats (snapshot_month, product_name, total_entries)
    SELECT v_month, product_name, COUNT(*)
    FROM (
        SELECT
            upper(left(trim(entry->>'nom'), 1))
                || lower(substring(trim(entry->>'nom') from 2)) AS product_name
        FROM (
            SELECT CASE
                WHEN jsonb_typeof(brief) = 'string' THEN NULLIF(brief#>>'{}', '')::jsonb
                ELSE brief
            END AS brief_json
            FROM public.client_crm
            WHERE brief IS NOT NULL
        ) parsed
        CROSS JOIN LATERAL jsonb_array_elements(
            CASE WHEN jsonb_typeof(parsed.brief_json->'recherche') = 'array'
                 THEN parsed.brief_json->'recherche'
                 ELSE '[]'::jsonb
            END
        ) AS entry
        WHERE trim(entry->>'nom') <> ''
    ) named_entries
    GROUP BY product_name;
END;
$$;

-- ── 5. Planification pg_cron (1er de chaque mois, 02:00 UTC) ─────────────
-- Réutilise le nom de job de l'ancienne fonction : un seul job de ce nom
-- doit exister, ce bloc le reschedule sur la nouvelle fonction.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'pg_cron') THEN
        BEGIN
            CREATE EXTENSION IF NOT EXISTS pg_cron;
        EXCEPTION WHEN OTHERS THEN
            RAISE NOTICE 'pg_cron non installable ici (%).', SQLERRM;
        END;
    END IF;

    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
        IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'crm-produit-recherche-monthly-snapshot') THEN
            PERFORM cron.unschedule('crm-produit-recherche-monthly-snapshot');
        END IF;
        PERFORM cron.schedule(
            'crm-produit-recherche-monthly-snapshot',
            '0 2 1 * *',
            $cmd$ SELECT public.snapshot_produit_recherche_monthly_stats(); $cmd$
        );
    END IF;
END $$;

-- ── 6. Backfill immédiat du mois en cours ────────────────────────────────

SELECT public.snapshot_produit_recherche_monthly_stats();

COMMIT;
