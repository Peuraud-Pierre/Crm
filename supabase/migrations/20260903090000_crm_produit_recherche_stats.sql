-- ============================================================
-- Courbe de tendance « Produits recherchés » (CRM Analytics)
-- Date: 2026-09-03
--
-- Les entrées brief.recherche[] (client_crm) n'ont pas de date propre :
-- impossible de reconstituer un historique après coup. On enregistre donc
-- une photo mensuelle du total courant, via un job pg_cron, dans une
-- nouvelle table dédiée. Voir
-- docs/superpowers/specs/2026-09-03-crm-produit-recherche-trend-design.md
--
-- Idempotent (guards IF NOT EXISTS / DROP POLICY IF EXISTS / cron.unschedule).
-- ============================================================

BEGIN;

-- ── 1. Table ────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.crm_produit_recherche_stats (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_month date NOT NULL UNIQUE,
    total_entries  integer NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- ── 2. RLS : lecture gatée sur crm.view, pas d'écriture applicative ──────

ALTER TABLE public.crm_produit_recherche_stats ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "crm.view can read produit recherche stats" ON public.crm_produit_recherche_stats;
CREATE POLICY "crm.view can read produit recherche stats"
    ON public.crm_produit_recherche_stats FOR SELECT
    TO authenticated
    USING (public.user_has_permission(auth.uid(), 'crm.view'));

-- ── 3. Fonction de snapshot ───────────────────────────────────────────────
-- brief peut être un jsonb natif OU une chaîne JSON encodée (cas connu côté
-- front : Client.brief?: FicheAppro | string | null) — on gère les deux.

CREATE OR REPLACE FUNCTION public.snapshot_produit_recherche_stats()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
    v_total integer;
BEGIN
    SELECT COALESCE(SUM(jsonb_array_length(parsed.brief_json->'recherche')), 0)
    INTO v_total
    FROM (
        SELECT CASE
            WHEN jsonb_typeof(brief) = 'string' THEN NULLIF(brief#>>'{}', '')::jsonb
            ELSE brief
        END AS brief_json
        FROM public.client_crm
        WHERE brief IS NOT NULL
    ) parsed
    WHERE jsonb_typeof(parsed.brief_json->'recherche') = 'array';

    INSERT INTO public.crm_produit_recherche_stats (snapshot_month, total_entries)
    VALUES (date_trunc('month', now())::date, v_total)
    ON CONFLICT (snapshot_month)
    DO UPDATE SET total_entries = EXCLUDED.total_entries;
END;
$$;

-- ── 4. Planification pg_cron (1er de chaque mois, 02:00 UTC) ─────────────
-- Pattern identique à 20260707150000_arrivage_invoice_reminder_cron.sql.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'pg_cron') THEN
        BEGIN
            CREATE EXTENSION IF NOT EXISTS pg_cron;
        EXCEPTION WHEN OTHERS THEN
            RAISE NOTICE 'pg_cron non installable ici (%).', SQLERRM;
        END;
    END IF;

    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
        IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'crm-produit-recherche-monthly-snapshot') THEN
            PERFORM cron.unschedule('crm-produit-recherche-monthly-snapshot');
        END IF;
        PERFORM cron.schedule(
            'crm-produit-recherche-monthly-snapshot',
            '0 2 1 * *',
            $cmd$ SELECT public.snapshot_produit_recherche_stats(); $cmd$
        );
    END IF;
END $$;

-- ── 5. Backfill immédiat du mois en cours ────────────────────────────────

SELECT public.snapshot_produit_recherche_stats();

COMMIT;
