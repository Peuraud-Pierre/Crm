-- ============================================================
-- Options dynamiques du brief CRM (brief_cat)
--
-- colonneBrief.tsx (fiche d'appro client) affichait 7 listes de valeurs
-- (plateformes, provenances, localisations, produits, marques, styles,
-- matières) codées en dur dans le composant : toute modification exigeait
-- un déploiement. Cette table centralise ces 7 listes pour les rendre
-- éditables depuis l'administration, avec activation/désactivation.
--
-- Table créée manuellement en base par l'utilisateur (structure reprise
-- ici pour la reproductibilité inter-environnements) :
--   type       = la valeur affichée en badge (ex: "Vinted")
--   categorie  = le discriminant de liste (ex: "plateformes")
--   available  = actif / inactif (soft-disable)
--
-- Pas de renommage de `type` en place côté admin (imposé côté front, pas
-- contraint ici en SQL) : les briefs déjà enregistrés référencent une
-- valeur par sa chaîne exacte dans le JSON `client_crm.brief` — renommer
-- désynchroniserait silencieusement les anciennes fiches. Désactiver
-- (`available = false`) + créer une nouvelle valeur est le chemin d'édition.
--
-- Permission : lecture ouverte à qui a déjà 'crm.view', écriture réservée
-- à 'crm.brief_options.manage' (nouvelle permission, seedée sur le même
-- périmètre que 'crm.view' — même modèle que 'bibliotheque.manage' dans
-- 20260715130000_bibliotheque_manage_permission.sql).
--
-- Idempotent (guards NOT EXISTS / IF NOT EXISTS / DROP POLICY IF EXISTS).
-- ============================================================

BEGIN;

-- ── 1. Table (déjà créée manuellement — IF NOT EXISTS pour les autres environnements) ──

CREATE TABLE IF NOT EXISTS public.brief_cat (
    id          bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    type        text NOT NULL,
    categorie   text NULL CHECK (categorie IS NULL OR categorie IN (
                    'plateformes', 'provenances', 'localisations',
                    'produits', 'marques', 'styles', 'matieres'
                )),
    available   boolean NULL DEFAULT true,
    CONSTRAINT brief_cat_pkey PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS brief_cat_categorie_available_idx
    ON public.brief_cat (categorie, available);

-- ── 2. Catalogue de permissions ────────────────────────────────────────

INSERT INTO public.permissions (code, label, category)
SELECT 'crm.brief_options.manage', 'Gérer les listes du brief CRM (plateformes, styles...)', 'crm'
WHERE NOT EXISTS (
    SELECT 1 FROM public.permissions WHERE code = 'crm.brief_options.manage'
);

-- ── 3. Octroi : même périmètre que crm.view aujourd'hui ────────────────

INSERT INTO public.roles_permissions (role_id, permission_id)
SELECT rp.role_id, target.id
FROM public.roles_permissions rp
JOIN public.permissions view_perm ON view_perm.id = rp.permission_id AND view_perm.code = 'crm.view'
JOIN public.permissions target    ON target.code  = 'crm.brief_options.manage'
WHERE NOT EXISTS (
    SELECT 1 FROM public.roles_permissions x
    WHERE x.role_id = rp.role_id AND x.permission_id = target.id
);

INSERT INTO public.services_permissions (service_id, permission_id)
SELECT sp.service_id, target.id
FROM public.services_permissions sp
JOIN public.permissions view_perm ON view_perm.id = sp.permission_id AND view_perm.code = 'crm.view'
JOIN public.permissions target    ON target.code  = 'crm.brief_options.manage'
WHERE NOT EXISTS (
    SELECT 1 FROM public.services_permissions x
    WHERE x.service_id = sp.service_id AND x.permission_id = target.id
);

-- ── 4. RLS : lecture gatée sur crm.view, écriture sur crm.brief_options.manage ──

ALTER TABLE public.brief_cat ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "crm.view can read brief options" ON public.brief_cat;
CREATE POLICY "crm.view can read brief options"
    ON public.brief_cat FOR SELECT
    TO authenticated
    USING (public.user_has_permission(auth.uid(), 'crm.view'));

DROP POLICY IF EXISTS "crm.brief_options.manage can insert brief options" ON public.brief_cat;
CREATE POLICY "crm.brief_options.manage can insert brief options"
    ON public.brief_cat FOR INSERT
    TO authenticated
    WITH CHECK (public.user_has_permission(auth.uid(), 'crm.brief_options.manage'));

DROP POLICY IF EXISTS "crm.brief_options.manage can update brief options" ON public.brief_cat;
CREATE POLICY "crm.brief_options.manage can update brief options"
    ON public.brief_cat FOR UPDATE
    TO authenticated
    USING (public.user_has_permission(auth.uid(), 'crm.brief_options.manage'))
    WITH CHECK (public.user_has_permission(auth.uid(), 'crm.brief_options.manage'));

DROP POLICY IF EXISTS "crm.brief_options.manage can delete brief options" ON public.brief_cat;
CREATE POLICY "crm.brief_options.manage can delete brief options"
    ON public.brief_cat FOR DELETE
    TO authenticated
    USING (public.user_has_permission(auth.uid(), 'crm.brief_options.manage'));

